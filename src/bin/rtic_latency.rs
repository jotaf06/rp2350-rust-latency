//! RTIC 2: the same measurement with a preemptive, priority-based framework
//! (Stack Resource Policy; BASEPRI on the RP2350, interrupt masking on the
//! RP2040's Cortex-M0+).
//!
//! * hardware task bound to the PWM wrap interrupt (the event ISR), priority 4;
//! * software task `measured`, priority 3, spawned by the ISR with the
//!   timestamp as message — RTIC's usual run-to-completion pattern;
//! * CPU load and a background task (USB + batch loop) at priority 1.
//!
//! One binary covers S0 and S1: batches with L = 0 (idle), 10, 100, 1000 µs.
//! Since the measured task has a higher priority than the load, the load is
//! preempted and the latency should not depend on L.
//!
//! embassy-rp is used only as HAL/PAC (clock, USB driver, pin setup); no
//! Embassy executor runs here.
//!
//! The app is generated by `latency_app!` because RTIC's `binds = ...` needs
//! the interrupt *name*, which differs between the chips (see `chip.rs`).

#![no_std]
#![no_main]
// Code generated by #[rtic::app] gets this crate's edition (2024) lints when
// the app is expanded from a macro_rules; the unsafe calls are RTIC's own.
#![allow(unsafe_op_in_unsafe_fn)]

use panic_halt as _;

macro_rules! latency_app {
    ($event_irq:ident) => {
#[rtic::app(device = embassy_rp::pac, peripherals = false, dispatchers = [SWI_IRQ_0, SWI_IRQ_1])]
mod app {
    use embassy_futures::join::join;
    use embassy_rp::pac::Interrupt;
    use rp2350_rust_latency::board::Board;
    use rp2350_rust_latency::{board, chip, measure, report, scenario, tasks};

    /// NVIC priority byte for the HAL's own interrupts (time driver, USB):
    /// RTIC logical priority 2, i.e. below both measured tasks and above the
    /// background tasks. `(levels - 2) << (8 - bits)`: 0xE0 with the RP2350's
    /// 4 priority bits, 0x80 with the RP2040's 2.
    const HAL_IRQ_PRIORITY: u8 =
        ((1u8 << chip::NVIC_PRIO_BITS) - 2) << (8 - chip::NVIC_PRIO_BITS);

    #[shared]
    struct Shared {}

    #[local]
    struct Local {
        board: Option<Board>,
    }

    #[init]
    fn init(mut cx: init::Context) -> (Shared, Local) {
        let b = board::init_hw();
        // SAFETY: only lowers priorities below every RTIC resource ceiling in use.
        unsafe {
            cx.core
                .NVIC
                .set_priority(chip::TIMER_IRQ, HAL_IRQ_PRIORITY);
            cx.core
                .NVIC
                .set_priority(Interrupt::USBCTRL_IRQ, HAL_IRQ_PRIORITY);
        }

        load::spawn().ok();
        background::spawn().ok();

        (Shared {}, Local { board: Some(b) })
    }

    /// The event: PWM slice 0 wrapped. Same instrumentation as the Embassy
    /// binaries; "signalling the task" is an RTIC `spawn` with a message.
    #[task(binds = $event_irq, priority = 4)]
    fn on_event(_cx: on_event::Context) {
        let t_isr_start = measure::isr_begin();
        let _ = measured::spawn(t_isr_start, measure::isr_next_seq());
        measure::isr_end();
    }

    /// The task under measurement.
    #[task(priority = 3)]
    async fn measured(_cx: measured::Context, t_isr_start: u32, seq: u32) {
        let t_task = measure::task_begin(); // first instruction of the task
        measure::record(t_isr_start, seq, t_task);
    }

    #[task(priority = 1)]
    async fn load(_cx: load::Context) {
        tasks::load_loop().await
    }

    /// USB stack and batch loop, joined in one task: the embassy-usb types are
    /// not `Send`, so they are created here instead of in `init`.
    #[task(priority = 1, local = [board])]
    async fn background(cx: background::Context) {
        let b = cx.local.board.take().unwrap();
        let (mut usb, serial) = report::usb_init(b.usb);
        let batches = scenario::run_polling(
            "rtic_latency",
            "rtic",
            &scenario::IDLE_AND_LOAD_BATCHES,
            b.clk_sys_hz,
            b.led,
            serial,
        );
        join(usb.run(), batches).await;
    }
}
    };
}

#[cfg(feature = "rp2350")]
latency_app!(PWM_IRQ_WRAP_0);
#[cfg(feature = "rp2040")]
latency_app!(PWM_IRQ_WRAP);
