#!/usr/bin/env python3
"""Generate tools/sample.log: a SYNTHETIC log, only for testing analyze.py.

The numbers come from a random generator with a fixed seed. They are not
measurements and say nothing about the real hardware.
"""

import random
from pathlib import Path

rng = random.Random(2350)
CLK = 150_000_000
N = 2000


def batch(name, exec_, profile, opt, div, top, load_us, ntasks, no, base, spread):
    out = [
        f"META,synthetic=1,bin={name},exec={exec_},profile={profile},opt={opt},clk_sys_hz={CLK},"
        f"pwm_div={div},pwm_top={top},load_us={load_us},ntasks={ntasks},n={N},discarded=0,warmup=50,"
        f"batch={no},git=synthetic"
    ]
    for i in range(N):
        cold = 40 if i < 3 else 0  # pretend the first events are slower
        irq = base[0] + cold + rng.randint(0, 4)
        isr = base[1] + cold + rng.randint(0, 8)
        sched = base[2] + cold + rng.randint(0, 12)
        if spread:  # cooperative executor behind a load: uniform extra delay up to L
            sched += rng.randint(0, spread * (CLK // 1_000_000))
        t = [max(1, v // div) for v in (irq, isr, sched)]
        out.append(f"SAMPLE,{i},{t[0]},{t[1]},{t[2]},{sum(t)},{1 if i < 50 else 0}")
    out.append("DONE")
    return out


lines = [
    "# SYNTHETIC DATA - generated by tools/gen_sample_log.py to test tools/analyze.py.",
    "# These are NOT measurements. Do not use these numbers for anything.",
]
no = 0
for profile, opt, k in (("release", "3", 1.0), ("release-z", "z", 1.3)):
    b = lambda *v: tuple(int(x * k) for x in v)
    lines += batch("s0_thread_idle", "thread", profile, opt, 1, 15449, 0, 0, no, b(40, 120, 300), 0)
    lines += batch("s0_irq_idle", "irq", profile, opt, 1, 15449, 0, 0, no, b(40, 130, 200), 0)
    for (div, top), load in (((1, 15449), 10), ((1, 38549), 100), ((6, 62574), 1000)):
        lines += batch("s1_thread_load", "thread", profile, opt, div, top, load, 0, no, b(40, 120, 300), load)
        lines += batch("s1_irq_load", "irq", profile, opt, div, top, load, 0, no, b(40, 130, 200), 0)
        no += 1

Path(__file__).with_name("sample.log").write_text("\n".join(lines) + "\n")
print("wrote tools/sample.log (synthetic)")
